const one = (sql, opts) => parseSql(sql, opts)[0];

// ------------------------------------------------------------------ lexer / splitter

test('splitter: dollar-quoted bodies keep their semicolons', () => {
  const s = splitStatements("CREATE FUNCTION f() RETURNS int AS $$ BEGIN; SELECT 1; END $$ LANGUAGE plpgsql; SELECT 2;");
  assert.equal(s.length, 2);
  assert.match(s[0].text, /LANGUAGE plpgsql$/);
});

test('splitter: tagged dollar quotes', () => {
  const s = splitStatements('DO $body$ BEGIN PERFORM 1; END $body$; SELECT 1;');
  assert.equal(s.length, 2);
});

test('splitter: E-strings with escaped quotes, and doubled quotes', () => {
  const s = splitStatements("SELECT E'it\\'s; ok'; SELECT 'a''b;c';");
  assert.equal(s.length, 2);
});

test('splitter: quoted identifiers contain semicolons and quotes', () => {
  const s = splitStatements('SELECT "a;b" FROM "t""x"; SELECT `c;d` FROM t;', { dialect: 'mysql' });
  assert.equal(s.length, 2);
  assert.equal(tokenize('"t""x"')[0].v, 't"x');
});

test('splitter: bracket identifiers in T-SQL/SQLite only', () => {
  assert.equal(tokenize('[my col]', { dialect: 'tsql' })[0].t, 'qident');
  assert.equal(tokenize('int[]', { dialect: 'postgresql' }).length, 3);
});

test('splitter: line and nested block comments', () => {
  const s = splitStatements('-- a; b\nSELECT 1; /* x; /* y; */ z; */ SELECT 2');
  assert.equal(s.length, 2);
  assert.equal(s[1].line, 2);
});

test('splitter: MySQL DELIMITER scripts', () => {
  const sql = 'DELIMITER //\nCREATE TRIGGER t BEFORE INSERT ON a FOR EACH ROW BEGIN SET @x = 1; SET @y = 2; END//\nDELIMITER ;\nSELECT 1;';
  const s = splitStatements(sql, { dialect: 'mysql' });
  assert.equal(s.length, 2);
  assert.match(s[0].text, /SET @y = 2; END$/);
});

test('splitter: GO batch separators', () => {
  const s = splitStatements('SELECT 1\nGO\nSELECT 2\nGO 5\n', { dialect: 'tsql' });
  assert.equal(s.length, 2);
});

test('splitter: SQLite trigger bodies stay whole', () => {
  const sql = 'CREATE TRIGGER tr AFTER INSERT ON a BEGIN UPDATE b SET x = 1; DELETE FROM c; END; SELECT 1;';
  const s = splitStatements(sql, { dialect: 'sqlite' });
  assert.equal(s.length, 2);
});

test('splitter: unterminated constructs do not throw', () => {
  for (const sql of ["SELECT 'abc", 'SELECT "abc', '/* never closed', '$$ open', 'SELECT `x']) {
    assert.doesNotThrow(() => splitStatements(sql));
  }
});

