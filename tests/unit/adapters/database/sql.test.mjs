test('parser does not throw on 1000 random byte strings (seeded)', () => {
  const rnd = prng(0x5eed);
  const alphabet = [...'abcSELECTFROMWHERE CREATE TABLE ALTER ;,()"\'`$[]{}--/*\\\n\t.=:<>+*#@!'];
  for (let i = 0; i < 1000; i++) {
    const len = Math.floor(rnd() * 200);
    let s = '';
    for (let j = 0; j < len; j++) {
      const r = rnd();
      s += r < 0.5 ? alphabet[Math.floor(rnd() * alphabet.length)] : String.fromCharCode(Math.floor(rnd() * 256));
    }
    for (const dialect of ['postgresql', 'mysql', 'sqlite', 'tsql']) {
      assert.doesNotThrow(() => parseSql(s, { dialect }), `seed iteration ${i} (${dialect})`);
    }
  }
});

test('parser does not throw on mutated real statements', () => {
  const rnd = prng(42);
  const base = [
    'CREATE TABLE t (id int PRIMARY KEY, c varchar(10) DEFAULT now() REFERENCES u (id) ON DELETE CASCADE)',
    'ALTER TABLE t ADD COLUMN c int, ALTER COLUMN d TYPE text USING d::text, ADD CONSTRAINT k FOREIGN KEY (a) REFERENCES b NOT VALID',
    'WITH x AS (SELECT * FROM a JOIN b ON a.id = b.id) UPDATE t SET a = 1 FROM x WHERE t.id = x.id',
    'CREATE UNIQUE INDEX CONCURRENTLY i ON t USING gin (lower(a)) WHERE b > 0',
  ];
  for (let i = 0; i < 400; i++) {
    const b = base[i % base.length];
    const cut = Math.floor(rnd() * b.length);
    const mutated = rnd() < 0.5 ? b.slice(0, cut) : b.slice(0, cut) + b.slice(cut + Math.floor(rnd() * 10));
    assert.doesNotThrow(() => parseSql(mutated), mutated);
  }
});
