test('create table: columns, types, defaults, volatility', () => {
  const st = one(`CREATE TABLE IF NOT EXISTS public.t (
    id bigserial PRIMARY KEY,
    name character varying(255) NOT NULL DEFAULT 'x',
    amount numeric(10, 2) DEFAULT 0,
    at timestamp with time zone DEFAULT now(),
    token uuid DEFAULT gen_random_uuid(),
    tags text[] DEFAULT '{}'::text[],
    g int GENERATED ALWAYS AS (amount * 2) STORED,
    ident bigint GENERATED BY DEFAULT AS IDENTITY,
    c text COLLATE "C"
  )`);
  assert.equal(st.kind, 'create_table');
  assert.equal(st.if_not_exists, true);
  assert.deepEqual(st.table, { schema: 'public', name: 't', db: null });
  const col = Object.fromEntries(st.columns.map((c) => [c.name, c]));
  assert.equal(col.id.identity, 'serial');
  assert.equal(col.id.nullable, false);
  assert.equal(col.name.type, 'character varying(255)');
  assert.equal(col.name.default.expr, "'x'");
  assert.equal(col.name.default.kind, 'literal');
  assert.equal(col.amount.type, 'numeric(10,2)');
  assert.equal(col.at.type, 'timestamp with time zone');
  assert.equal(col.at.default.stable_function, true);
  assert.equal(col.at.default.volatile, false);
  assert.equal(col.token.default.volatile, true);
  assert.equal(col.tags.type, 'text[]');
  assert.deepEqual(col.g.generated, { expr: 'amount * 2', stored: true });
  assert.equal(col.ident.identity, 'by default');
  assert.equal(col.c.collation, 'C');
});

test('create table: inline and table constraints', () => {
  const st = one(`CREATE TABLE o (
    id int PRIMARY KEY,
    cid int NOT NULL REFERENCES customers (id) ON DELETE SET NULL ON UPDATE CASCADE,
    sku text UNIQUE,
    qty int CHECK (qty > 0),
    CONSTRAINT o_uq UNIQUE (cid, sku),
    FOREIGN KEY (cid) REFERENCES c2 (id) ON DELETE CASCADE NOT VALID,
    CHECK (qty < 1000)
  )`);
  const kinds = st.constraints.map((k) => k.kind).sort();
  assert.deepEqual(kinds, ['check', 'check', 'foreign_key', 'foreign_key', 'primary_key', 'unique', 'unique']);
  const fk = st.constraints.find((k) => k.kind === 'foreign_key' && k.ref_table.name === 'customers');
  assert.equal(fk.on_delete, 'SET NULL');
  assert.equal(fk.on_update, 'CASCADE');
  const fk2 = st.constraints.find((k) => k.ref_table?.name === 'c2');
  assert.equal(fk2.on_delete, 'CASCADE');
  assert.equal(fk2.not_valid, true);
  assert.equal(st.constraints.find((k) => k.name === 'o_uq').columns.join(), 'cid,sku');
});

test('create table: partitioning, LIKE, partition of, CTAS', () => {
  assert.deepEqual(one('CREATE TABLE m (ts timestamptz) PARTITION BY RANGE (ts)').partition_by, { type: 'RANGE', columns: ['ts'] });
  assert.equal(one('CREATE TABLE a (LIKE b INCLUDING ALL)').like[0].name, 'b');
  assert.equal(one("CREATE TABLE m1 PARTITION OF m FOR VALUES FROM ('2024-01-01') TO ('2024-02-01')").partition_of.name, 'm');
  const ctas = one('CREATE TABLE s AS SELECT * FROM src JOIN other o ON o.id = src.id');
  assert.equal(ctas.as_select, true);
  assert.deepEqual(ctas.source_tables.map((t) => t.name).sort(), ['other', 'src']);
});

