test('DML: target table and WHERE detection', () => {
  const u = one('UPDATE ONLY public.t SET a = 1');
  assert.deepEqual([u.kind, u.table.name, u.table.schema, u.has_where], ['update', 't', 'public', false]);
  assert.equal(one('UPDATE t SET a = 1 WHERE id = 2').has_where, true);
  assert.equal(one('UPDATE t SET a = (SELECT max(x) FROM u WHERE u.id = 1)').has_where, false);
  const d = one('DELETE FROM t');
  assert.deepEqual([d.kind, d.has_where], ['delete', false]);
  assert.equal(one('DELETE FROM t WHERE x < 3').has_where, true);
  const i = one('INSERT INTO t (a) SELECT x FROM u');
  assert.deepEqual([i.kind, i.table.name, i.reads.map((r) => r.name)], ['insert', 't', ['u']]);
  const m = one('MERGE INTO t USING s ON t.id = s.id WHEN MATCHED THEN UPDATE SET a = s.a');
  assert.deepEqual([m.kind, m.table.name, m.reads.map((r) => r.name)], ['merge', 't', ['s']]);
  const wd = one('WITH x AS (SELECT 1) DELETE FROM t');
  assert.deepEqual([wd.kind, wd.table.name, wd.has_where], ['delete', 't', false]);
  assert.equal(one('INSERT INTO t VALUES (1) ON CONFLICT (id) DO UPDATE SET a = 2').table.name, 't');
  const mysqlDel = one('DELETE a FROM a JOIN b ON a.id = b.id WHERE b.x = 1', { dialect: 'mysql' });
  assert.deepEqual([mysqlDel.table.name, mysqlDel.reads.map((r) => r.name)], ['a', ['a', 'b']]);
});

test('SELECT: FROM/JOIN extraction, schema-qualified names, CTEs excluded', () => {
  const st = one(`WITH recent AS (SELECT * FROM events e WHERE e.at > now()),
      big AS NOT MATERIALIZED (SELECT * FROM recent)
    SELECT * FROM recent r
      JOIN public.users u ON u.id = r.user_id
      LEFT JOIN LATERAL (SELECT 1 FROM audit.logs l WHERE l.u = u.id) x ON true
      , plain p
    WHERE EXTRACT(epoch FROM r.at) > 0`);
  assert.equal(st.kind, 'select');
  const names = st.reads.map((r) => `${r.schema ?? ''}.${r.name}`).sort();
  assert.deepEqual(names, ['.events', '.plain', 'audit.logs', 'public.users']);
  assert.deepEqual(st.ctes, ['big', 'recent']);
  assert.deepEqual(st.joins, [], 'joins against a CTE are not table joins');
  const j = one('SELECT 1 FROM a x JOIN b y ON x.id = y.id LEFT JOIN s.c ON c.id = y.id');
  assert.deepEqual(j.joins.map((p) => `${p.left.name}>${p.right.schema ?? ''}.${p.right.name}`), ['a>.b', 'b>s.c']);
});

